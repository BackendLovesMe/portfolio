-- Run this in Supabase Dashboard -> SQL Editor.
create table if not exists public.portfolio_leads (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null,
  reason text not null check (reason in ('Recruitment', 'Networking', 'Engineering', 'Other')),
  consent boolean not null default false check (consent = true),
  created_at timestamptz not null default now()
);

-- Normalize email for duplicate detection and uniqueness.
create unique index if not exists portfolio_leads_email_lower_uidx
  on public.portfolio_leads (lower(email));

alter table public.portfolio_leads enable row level security;

-- No anon/authenticated policies are intentionally created. Access is through
-- server-side routes using the service-role key, which must never be exposed.
